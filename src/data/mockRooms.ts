import { Room, TimeSlot } from '../types/room';
import { getAvailableDates, STANDARD_SLOTS } from '../utils/conflictChecker';

function generateRoomSlots(occupiedSlotsIndexes: number[]): { [date: string]: TimeSlot[] } {
  const dates = getAvailableDates();
  const schedule: { [date: string]: TimeSlot[] } = {};

  dates.forEach((d, dateIndex) => {
    schedule[d.key] = STANDARD_SLOTS.map((slot, slotIndex) => {
      const isOccupied = occupiedSlotsIndexes.includes((slotIndex + dateIndex) % STANDARD_SLOTS.length);
      return {
        ...slot,
        isBooked: isOccupied,
        bookedBy: isOccupied ? (slotIndex % 2 === 0 ? 'Nhóm Đồ Án Tốt Nghiệp VKU' : 'Nhóm Nghiên Cứu AI') : undefined,
      };
    });
  });

  return schedule;
}

